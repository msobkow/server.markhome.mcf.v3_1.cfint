public interface ICFIntTenantEditObj
	extends ICFIntTenantObj, ICFSecTenantEditObj
{
	/*
	 *	create() may return a different instance than the
	 *	one used to invoke the operation.  All future references
	 *	should be to the returned instance, not the original
	 *	invoker.  You should lose all references to the original
	 *	invoker.
	 *
	 *	@return The created instance.
	 */
	ICFSecTenantObj create();

	/*
	 *	Update the instance.
	 */
	CFSecTenantEditObj update();

	/**
	 *	Set the user who created this instance.
	 *
	 *	@param	value	The ICFSecSecUserObj instance who created this instance.
	 */
	void setCreatedBy( ICFSecSecUserObj value );

	/**
	 *	Set the Calendar date-time this instance was created.
	 *
	 *	@param	value	The Calendar value for the create time of the instance.
	 */
	void setCreatedAt( LocalDateTime value );

	/**
	 *	Set the user who updated this instance.
	 *
	 *	@param	value	The ICFSecSecUserObj instance who updated this instance.
	 */
	void setUpdatedBy( ICFSecSecUserObj value );

	/**
	 *	Set the Calendar date-time this instance was updated.
	 *
	 *	@param	value	The Calendar value for the create time of the instance.
	 */
	void setUpdatedAt( LocalDateTime value );

	/**
	 *	Get the ICFSecClusterObj instance referenced by the Cluster key.
	 *
	 *	@return	The ICFSecClusterObj instance referenced by the Cluster key.
	 */
	ICFSecClusterObj getRequiredContainerCluster();

	/**
	 *	Get the required ICFSecClusterObj instance referenced by the Cluster key.
	 *
	 *	@return	The required ICFSecClusterObj instance referenced by the Cluster key.
	 */
	ICFSecClusterObj getRequiredContainerCluster( boolean forceRead );

	/**
	 *	Set the ICFSecClusterObj instance referenced by the Cluster key.
	 *
	 *	@param	value	the ICFSecClusterObj instance to be referenced by the Cluster key.
	 */
	void setRequiredContainerCluster( ICFSecClusterObj value );

	/**
	 *	Get a list ICFSecSecTentGrpObj instances referenced by the SecGroup key.
	 *
	 *	@return	The (potentially empty) list of ICFSecSecTentGrpObj instances referenced by the SecGroup key.
	 */
	List<ICFSecSecTentGrpObj> getOptionalComponentsSecGroup();

	/**
	 *	Get a list ICFSecSecTentRoleObj instances referenced by the SecRole key.
	 *
	 *	@return	The (potentially empty) list of ICFSecSecTentRoleObj instances referenced by the SecRole key.
	 */
	List<ICFSecSecTentRoleObj> getOptionalComponentsSecRole();

	/**
	 *	Get a list ICFIntTldObj instances referenced by the Tld key.
	 *
	 *	@return	The (potentially empty) list of ICFIntTldObj instances referenced by the Tld key.
	 */
	List<ICFIntTldObj> getOptionalComponentsTld();

	public void copyRecToOrig();
	public void copyOrigToRec();

}
